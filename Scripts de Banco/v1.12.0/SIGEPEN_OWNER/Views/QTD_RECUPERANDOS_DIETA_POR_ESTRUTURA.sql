-- SIGEPEN_OWNER_DES.QTD_RECUPERANDOS_DIETA_POR_ESTRUTURA source

CREATE OR REPLACE FORCE EDITIONABLE VIEW "SIGEPEN_OWNER_DES"."QTD_RECUPERANDOS_DIETA_POR_ESTRUTURA" ("ESTRUTURA_ID", "QTD_RECUPERANDOS_ESTRUTURA", "QTD_PADRAO", "QTD_ESPECIAL") AS 
  SELECT 
L.ESTRUTURA_ID, COUNT(PAS.RECUPERANDO_ID) QTD_RECUPERANDOS_ESTRUTURA
,SUM(CASE WHEN dr.ID IS null THEN 1 ELSE 0 END) AS QTD_padrao
,SUM(CASE WHEN dr.ID IS not null THEN 1 ELSE 0 END) AS QTD_especial
FROM PASSAGEM PAS
JOIN PASSAGEM_LOTACAO L on l.PASSAGEM_ID = pas.ID and L.DATA_SAIDA IS NULL
LEFT JOIN PEDIDO_TRANSITO PT on PT.RECUPERANDO_ID = PAS.RECUPERANDO_ID AND PT.DATA_CONCLUSAO IS NULL AND PT.STATUS IN ('SUSPENSO', 'EM_ANDAMENTO')
LEFT JOIN SIGEPEN_OWNER_DES.DIETA_RECUPERANDO dr ON dr.RECUPERANDO_ID = PAS.RECUPERANDO_ID AND dr.STATUS = 1
  GROUP BY L.ESTRUTURA_ID

;

GRANT SELECT, INSERT, UPDATE, DELETE ON SIGEPEN_OWNER_DES.QTD_RECUPERANDOS_DIETA_POR_ESTRUTURA TO SIGEPEN_USER_DES;