  DATA_EXPIRACAO     DATE,
  IS_PRIMEIRO_ACESSO NUMBER(1),
  LOGIN              VARCHAR2(11 CHAR),
  SALT               VARCHAR2(100 CHAR),
  SENHA              VARCHAR2(100 CHAR),
  STATUS             NUMBER(10),
  SERVIDOR_ID        NUMBER(19),
  EMAIL 			 VARCHAR2(100 CHAR)
)
TABLESPACE TBS_SIGEPEN_AUDIT_OWNER_D;

