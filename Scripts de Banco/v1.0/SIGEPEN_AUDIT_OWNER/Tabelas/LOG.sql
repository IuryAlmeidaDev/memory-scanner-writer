CREATE TABLE LOG
(
  ID        NUMBER(19) NOT NULL,
  DATALOG   TIMESTAMP(6),
  NIVEL     VARCHAR2(10 CHAR),
  LOGGER    VARCHAR2(150 CHAR),
  MESSAGE   VARCHAR2(255 CHAR),
  IP_ORIGEM   VARCHAR2(255 CHAR),
  USUARIO_ID   VARCHAR2(20),
  THROWABLE CLOB
)
TABLESPACE TBS_SIGEPEN_AUDIT_OWNER_D;

ALTER TABLE LOG ADD CONSTRAINT PK_LOG PRIMARY KEY (ID) USING INDEX TABLESPACE TBS_SIGEPEN_AUDIT_OWNER_I;

