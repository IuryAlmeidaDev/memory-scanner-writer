CREATE OR REPLACE VIEW TBS_SISTEMAS_OWNER.SIGEPEN_V_CRIME AS
SELECT DISTINCT
det.codg_detalhamento_legislacao,
LEG.CODG_LEGISLACAO,
LEG.NOME_LEGISLACAO,
DET.NUMR_ARTIGO, 
DET.NUMR_PARAGRAFO, 
DET.NUMR_INCISO, 
DET.NUMR_ALINEA,
DET.TEXTO_DETALHAMENTO_LEGISLACAO

FROM 

tbs_sistemas_owner.tbs_detalhamento_legislacao DET,
tbs_sistemas_owner.tbs_titulo_legislacao TIT,
tbs_sistemas_owner.tbs_legislacao LEG

WHERE 
LEG.STAT_LEGISLACAO = 'A'
AND det.stat_detalhe_legislacao = 'A'
AND LEG.CODG_LEGISLACAO = TIT.CODG_LEGISLACAO 
AND TIT.CODG_TITULO_LEGISLACAO = DET.CODG_TITULO_LEGISLACAO

ORDER BY 
LEG.CODG_LEGISLACAO,
DET.NUMR_ARTIGO, 
DET.NUMR_PARAGRAFO, 
DET.NUMR_INCISO, 
DET.NUMR_ALINEA;
  
  
  
