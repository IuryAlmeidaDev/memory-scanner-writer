CREATE OR REPLACE VIEW QTD_RECUPERANDOS_POR_ESTRUTURA AS
SELECT L.ESTRUTURA_ID, COUNT(PAS.RECUPERANDO_ID) QTD_RECUPERANDOS_ESTRUTURA
          FROM PASSAGEM PAS, PASSAGEM_LOTACAO L, PEDIDO_TRANSITO PT
         WHERE L.DATA_SAIDA IS NULL
           AND L.PASSAGEM_ID = PAS.ID
           AND PT.RECUPERANDO_ID(+) = PAS.RECUPERANDO_ID
           AND PT.DATA_CONCLUSAO(+) IS NULL
           AND PT.STATUS(+) IN ('SUSPENSO', 'EM_ANDAMENTO')
          GROUP BY L.ESTRUTURA_ID;