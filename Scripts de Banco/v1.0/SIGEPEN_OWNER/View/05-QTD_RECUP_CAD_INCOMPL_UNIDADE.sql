CREATE OR REPLACE VIEW QTD_RECUP_CAD_INCOMPL_UNIDADE AS
SELECT E.UNIDADEPRISIONAL_ID, COUNT(PAS.RECUPERANDO_ID) QTD_RECUPERANDO
FROM PASSAGEM                       PAS,
   PASSAGEM_LOTACAO               L,
   PEDIDO_TRANSITO                PT,
   SITUACAO_CADASTR_RECUP_SIMPLES S,
   ESTRUTURA                      E
WHERE L.DATA_SAIDA IS NULL
AND L.PASSAGEM_ID = PAS.ID
AND PT.RECUPERANDO_ID(+) = PAS.RECUPERANDO_ID
AND PT.DATA_CONCLUSAO(+) IS NULL
AND PT.STATUS(+) IN ('SUSPENSO', 'EM_ANDAMENTO')
AND S.ID = PAS.RECUPERANDO_ID
AND S.CADASTRO_COMPLETO = 0
AND L.ESTRUTURA_ID = E.ID
GROUP BY E.UNIDADEPRISIONAL_ID;