CREATE TABLE PESSOA
(
  ID                   NUMBER(19) NOT NULL,
  NOME                 VARCHAR2(80 CHAR) NOT NULL,
  NOME_MAE             VARCHAR2(80 CHAR) NOT NULL,
  NOME_PAI             VARCHAR2(80 CHAR),
  DATA_NASCIMENTO      DATE NOT NULL,
  SEXO                 VARCHAR2(10 CHAR),
  CIDADE_ID            NUMBER(19),
  NACIONALIDADE_ID     NUMBER(19),
  PAIS_ID              NUMBER(19),
  BIOMETRIA_ID		   NUMBER(19),
  AUTORIZACAO_CAD_ID   NUMBER(19)
)
TABLESPACE TBS_SIGEPEN_OWNER_D;

ALTER TABLE PESSOA ADD CONSTRAINT PK_PESSOA                   PRIMARY KEY (ID) USING INDEX TABLESPACE TBS_SIGEPEN_OWNER_I;
ALTER TABLE PESSOA ADD CONSTRAINT FK_PESSOA_CIDADE 			  FOREIGN KEY (CIDADE_ID) 			REFERENCES TBS_SISTEMAS_OWNER.TBS_MUNICIPIO (CODG_MUNICIPIO);
ALTER TABLE PESSOA ADD CONSTRAINT FK_PESSOA_NACIONALIDADE     FOREIGN KEY (NACIONALIDADE_ID)    REFERENCES TBS_SISTEMAS_OWNER.TBS_NACIONALIDADE (CODG_NACIONALIDADE);
ALTER TABLE PESSOA ADD CONSTRAINT FK_PESSOA_PAIS              FOREIGN KEY (PAIS_ID)             REFERENCES TBS_SISTEMAS_OWNER.TBS_PAIS (CODG_PAIS);
ALTER TABLE PESSOA ADD CONSTRAINT FK_PESSOA_BIOMETRIA	      FOREIGN KEY (BIOMETRIA_ID)        REFERENCES BIOMETRIA (ID);
ALTER TABLE PESSOA ADD CONSTRAINT FK_PESSOA_AUTORIZACAO_CAD   FOREIGN KEY (AUTORIZACAO_CAD_ID)	REFERENCES AUTORIZACAO_CADASTRO_BIO (ID);

