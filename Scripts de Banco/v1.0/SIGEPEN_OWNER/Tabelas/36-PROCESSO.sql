CREATE TABLE PROCESSO
(
  ID                    NUMBER(19) NOT NULL,
  DATA_FINALIZADO       DATE,
  NUMERO_INQUERITO      VARCHAR2(80 CHAR),
  NUMERO_OFICIO         VARCHAR2(80 CHAR),
  NUMERO_PROCESSO       VARCHAR2(80 CHAR),
  OBSERVACAO_FINALIZADO VARCHAR2(250 CHAR),
  STATUS_PROCESSO       VARCHAR2(255 CHAR),
  ANO NUMBER(19), 
  DIA NUMBER(19), 
  MES NUMBER(19),
  RECUPERANDO_ID        NUMBER(19)
)
TABLESPACE TBS_SIGEPEN_OWNER_D;

ALTER TABLE PROCESSO ADD CONSTRAINT PK_PROCESSO PRIMARY KEY (ID) USING INDEX TABLESPACE TBS_SIGEPEN_OWNER_I;
ALTER TABLE PROCESSO ADD CONSTRAINT FK_PROCESSO_RECUPERANDO FOREIGN KEY (RECUPERANDO_ID) REFERENCES RECUPERANDO (ID);

GRANT SELECT, INSERT, UPDATE, DELETE ON PROCESSO TO SIGEPEN_USER;