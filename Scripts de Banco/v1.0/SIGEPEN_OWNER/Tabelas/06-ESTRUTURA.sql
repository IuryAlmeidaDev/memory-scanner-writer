CREATE TABLE ESTRUTURA
(
  ID                  NUMBER(19) NOT NULL,
  CAPACIDADE          NUMBER(10),
  CELA                NUMBER(1),
  NOME                VARCHAR2(80 CHAR) NOT NULL,
  SITUACAO            NUMBER(10),
  ESTRUTURAPAI_ID     NUMBER(19),
  UNIDADEPRISIONAL_ID NUMBER(19)
)
TABLESPACE TBS_SIGEPEN_OWNER_D;

ALTER TABLE ESTRUTURA ADD CONSTRAINT PK_ESTRUTURA PRIMARY KEY (ID) USING INDEX TABLESPACE TBS_SIGEPEN_OWNER_I;
ALTER TABLE ESTRUTURA ADD CONSTRAINT FK_ESTRUTURA_ESTRUTURA_PAI FOREIGN KEY (ESTRUTURAPAI_ID) REFERENCES ESTRUTURA (ID);
ALTER TABLE ESTRUTURA ADD CONSTRAINT FK_ESTRUTURA_UNIDADE_PRISIONAL FOREIGN KEY (UNIDADEPRISIONAL_ID) REFERENCES UNIDADE_PRISIONAL (ID);

--FK UNIDADE_PRIOSIONAL_ESTRUTURA CRIADA APOS CRIAR ESTRUTURA

ALTER TABLE UNIDADE_PRISIONAL ADD CONSTRAINT FK_UNIDADE_PRISIONAL_ESTRUTURA  FOREIGN KEY (ESTRUTURA_ID) REFERENCES ESTRUTURA (ID); 

