CREATE TABLE REMANEJAMENTO
   (	
   	ID 						NUMBER(19,0) NOT NULL ENABLE, 
	DATA_CONCLUSAO 			TIMESTAMP (6), 
	DATA_INICIO 			TIMESTAMP (6), 
	OBSERVACAO 				VARCHAR2(250 CHAR), 
	RESULTADO 				VARCHAR2(250 CHAR), 
	STATUS 					VARCHAR2(255 CHAR),
	FOTO_ID 				NUMBER(19),	
	ESTRUTURA_DESTINO_ID 	NUMBER(19,0), 
	ESTRUTURA_ORIGEM_ID 	NUMBER(19,0), 
	PEDIDO_ID 				NUMBER(19,0), 
	UNIDADE_REMANEJADA_ID 	NUMBER(19,0) 
   )
  TABLESPACE TBS_SIGEPEN_OWNER_D;
  
  ALTER TABLE REMANEJAMENTO ADD CONSTRAINT PK_REMANEJAMENTO 					 PRIMARY KEY (ID) USING INDEX TABLESPACE TBS_SIGEPEN_OWNER_I;
  ALTER TABLE REMANEJAMENTO ADD CONSTRAINT FK_REMANEJ_ESTRUTURA_DESTINO 	 FOREIGN KEY (ESTRUTURA_DESTINO_ID)  REFERENCES ESTRUTURA (ID);
  ALTER TABLE REMANEJAMENTO ADD CONSTRAINT FK_REMANEJ_ESTRUTURA_ORIGEM	 FOREIGN KEY (ESTRUTURA_ORIGEM_ID)   REFERENCES ESTRUTURA (ID);
  ALTER TABLE REMANEJAMENTO ADD CONSTRAINT FK_REMANEJ_PEDIDO		 		 FOREIGN KEY (PEDIDO_ID)        	 REFERENCES PEDIDO_TRANSITO (ID);
  ALTER TABLE REMANEJAMENTO ADD CONSTRAINT FK_REMANEJ_UNIDADE_REMANEJADA	 FOREIGN KEY (UNIDADE_REMANEJADA_ID) REFERENCES UNIDADE_PRISIONAL (ID);
  ALTER TABLE REMANEJAMENTO ADD CONSTRAINT FK_REMANEJAMENTO_FOTO FOREIGN KEY (FOTO_ID) REFERENCES FOTO (ID);

  GRANT SELECT, INSERT, UPDATE, DELETE ON REMANEJAMENTO TO SIGEPEN_USER;
