CREATE OR REPLACE FUNCTION BUSCAESTRUTURANOMECOMPLETO (ID_ESTRUTURA IN NUMBER)
RETURN VARCHAR2
IS RESULTADO VARCHAR2(255);
BEGIN
  SELECT LISTAGG(E.NOME, ' > ') WITHIN GROUP(ORDER BY E.ID) CELA INTO RESULTADO
  FROM SIGEPEN_OWNER.ESTRUTURA E
 WHERE E.ESTRUTURAPAI_ID IS NOT NULL
 START WITH E.ID = ID_ESTRUTURA
CONNECT BY E.ID = PRIOR E.ESTRUTURAPAI_ID;

RETURN RESULTADO;
END;
