-- 1. Identificar e excluir itens de cardápios duplicados (mantendo apenas o mais recente por ID)
DELETE FROM SIGEPEN_OWNER.ITEM_CARDAPIO
WHERE CARDAPIO_ID IN (
    SELECT ID FROM SIGEPEN_OWNER.CARDAPIO c1
    WHERE EXISTS (
        SELECT 1 FROM SIGEPEN_OWNER.CARDAPIO c2
        WHERE c1.CONTRATO_ID = c2.CONTRATO_ID
          AND c1.SEMANA = c2.SEMANA
          AND c1.CODG_DIA_SEMANA = c2.CODG_DIA_SEMANA
          AND c1.TIPO_REFEICAO_ID = c2.TIPO_REFEICAO_ID
          AND c1.TIPO_DIETA_ID = c2.TIPO_DIETA_ID
          AND c1.ID < c2.ID
    )
);

-- 2. Excluir os cardápios duplicados (mantendo apenas o mais recente por ID)
DELETE FROM SIGEPEN_OWNER.CARDAPIO c1
WHERE EXISTS (
    SELECT 1 FROM SIGEPEN_OWNER.CARDAPIO c2
    WHERE c1.CONTRATO_ID = c2.CONTRATO_ID
      AND c1.SEMANA = c2.SEMANA
      AND c1.CODG_DIA_SEMANA = c2.CODG_DIA_SEMANA
      AND c1.TIPO_REFEICAO_ID = c2.TIPO_REFEICAO_ID
      AND c1.TIPO_DIETA_ID = c2.TIPO_DIETA_ID
      AND c1.ID < c2.ID
);

-- 3. Criar a constraint de unicidade
ALTER TABLE SIGEPEN_OWNER.CARDAPIO
ADD CONSTRAINT UK_CARDAPIO_REQUISITOS UNIQUE (CONTRATO_ID, SEMANA, CODG_DIA_SEMANA, TIPO_REFEICAO_ID, TIPO_DIETA_ID);
