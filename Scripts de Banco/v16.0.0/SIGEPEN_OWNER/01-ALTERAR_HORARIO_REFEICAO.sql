SET HORARIO_FIM = HORARIO,
    HORARIO_INICIO = LPAD(MOD(TO_NUMBER(NVL(SUBSTR(HORARIO, 1, 2), '0')) - 1 + 24, 24), 2, '0') || NVL(SUBSTR(HORARIO, 3, 2), '00') where ID is not null;

